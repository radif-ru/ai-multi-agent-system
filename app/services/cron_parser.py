"""Детерминированный парсер естественного языка → 5-польный cron.

Поддерживаемые паттерны:
- «каждый день в N» / «каждый день в N:MM»
- «каждый понедельник в N» / «по понедельникам в N»
- «по будням в N»
- «каждый час»
- «каждые N часов»
- «каждые N минут»
- «каждую неделю»
- «каждое N число месяца» / «N-го числа каждого месяца»

Если паттерн не распознан — возвращает `None` (fallback на LLM).
См. `_docs/scheduler.md`, спринт 15 задача 4.2.
"""

from __future__ import annotations

import re

# День недели: имя → номер (0=вс, 1=пн, ..., 6=сб)
_WEEKDAY_MAP: dict[str, str] = {
    "воскресенье": "0",
    "воскресенья": "0",
    "вс": "0",
    "понедельник": "1",
    "понедельники": "1",
    "понедельника": "1",
    "понедельникам": "1",
    "пн": "1",
    "вторник": "2",
    "вторники": "2",
    "вторника": "2",
    "вторникам": "2",
    "вт": "2",
    "среда": "3",
    "среду": "3",
    "среды": "3",
    "средам": "3",
    "ср": "3",
    "четверг": "4",
    "четверги": "4",
    "четверга": "4",
    "четвергам": "4",
    "чт": "4",
    "пятница": "5",
    "пятницу": "5",
    "пятницы": "5",
    "пятницам": "5",
    "пт": "5",
    "суббота": "6",
    "субботу": "6",
    "субботы": "6",
    "субботам": "6",
    "сб": "6",
}


def _parse_time(text: str) -> tuple[str, str] | None:
    """Извлечь час и минуту из текста. Возвращает (hour, minute) или None."""
    # «в 9» / «в 9:30» / «в 09:00» / «в 18:30»
    m = re.search(r"\bв\s+(\d{1,2}):(\d{2})\b", text)
    if m:
        h, mi = int(m.group(1)), int(m.group(2))
        if 0 <= h <= 23 and 0 <= mi <= 59:
            return str(h), str(mi)
    m = re.search(r"\bв\s+(\d{1,2})\b", text)
    if m:
        h = int(m.group(1))
        if 0 <= h <= 23:
            return str(h), "0"
    return None


def parse_cron(text: str) -> str | None:
    """Распарсить естественный язык в 5-польный cron.

    Возвращает cron-строку или None, если паттерн не распознан.
    """
    t = text.lower().strip()

    # --- каждый час ---
    if re.search(r"\bкаждый\s+час\b", t):
        return "0 * * * *"

    # --- каждые N часов ---
    m = re.search(r"\bкаждые\s+(\d+)\s+час", t)
    if m:
        n = int(m.group(1))
        if 1 <= n <= 23:
            return f"0 */{n} * * *"

    # --- каждые N минут ---
    m = re.search(r"\bкаждые\s+(\d+)\s+минут", t)
    if m:
        n = int(m.group(1))
        if 1 <= n <= 59:
            return f"*/{n} * * * *"

    # --- по будням в N ---
    if re.search(r"\bпо\s+будням\b", t):
        tm = _parse_time(t)
        if tm:
            return f"{tm[1]} {tm[0]} * * 1-5"
        return None

    # --- каждую неделю ---
    if re.search(r"\bкаждую\s+недел", t):
        return "0 0 * * 0"

    # --- каждый/по <день_недели> в N ---
    for name, dow in _WEEKDAY_MAP.items():
        if re.search(rf"\b(?:каждый|каждую|по)\s+{name}\b", t):
            tm = _parse_time(t)
            if tm:
                return f"{tm[1]} {tm[0]} * * {dow}"
            return None

    # --- каждое N число месяца / N-го числа каждого месяца ---
    m = re.search(
        r"\b(?:каждое|каждого)?\s*(\d{1,2})(?:[-е](?:го|е|ое)?)?"
        r"\s+(?:числ[ао]\s+)?(?:месяца|каждого\s+месяца)",
        t,
    )
    if m:
        day = int(m.group(1))
        if 1 <= day <= 31:
            tm = _parse_time(t)
            if tm:
                return f"{tm[1]} {tm[0]} {day} * *"
            return f"0 0 {day} * *"

    # --- каждый день в N ---
    if re.search(r"\bкаждый\s+день\b", t):
        tm = _parse_time(t)
        if tm:
            return f"{tm[1]} {tm[0]} * * *"
        return None

    return None
